function refreshedBank(bank) {
 return bank.categories.flatMap(category=>{
  const rows=refreshedSets[category.id];
  if(!rows||rows.length!==15)throw new Error('Incomplete question pools: '+category.id);
  const first=rows.map((row,i)=>{
   const tier=i%3, q={...row,id:category.id+'-v3-'+i,categoryId:category.id,
    pool:Math.floor(i/3),points:[200,400,600][tier],difficulty:['easy','medium','hard'][tier],
    type:row.type||'text',explanation:'',alternatives:[],status:'published'};
   if(category.id==='quiz'){
    q.type='multiple';const options=[q.answer,...freshQuizDistractors[i]];
    q.options=options.slice(i%4).concat(options.slice(0,i%4));
   }
   return q;
  });
  // Fill the opposite column from distinct, difficulty-reviewed questions.
  // Keep contextual images instead of restoring the old answer-specific photos.
  const originals=bank.questions.filter(q=>q.categoryId===category.id).concat(extraQuestions(category));
  const candidates=[];
  for(let pool=0;pool<5;pool++)candidates.push(...balancePack(originals.slice(pool*6,pool*6+6),category.id,pool));
  const signature=q=>q.type==='charades'?q.answer:q.text;
  const used=new Set(first.map(signature));
  const second=first.map((paired,i)=>{
   const candidatesAtTier=candidates.filter(q=>q.points===paired.points).map(q=>{
    const next={...q};
    if(next.followUp){next.text=next.followUp.prompt;next.answer=next.followUp.answer;delete next.followUp;}
    return next;
   });
   let chosen=candidatesAtTier.find(q=>!used.has(signature(q)));
   if(oppositeCards[category.id])chosen={...paired,answer:oppositeCards[category.id][i]};
   if(category.id==='whoanime'){
    const [text,answer]=oppositeAnime[i].split('|');
    chosen={...paired,text,answer};
   }
   if(!chosen)throw new Error('Missing distinct question: '+category.id+' '+paired.points);
   used.add(signature(chosen));
   return {...chosen,id:category.id+'-v4-b-'+i,pool:paired.pool,image:paired.image,explanation:'',source:undefined};
  });
  return first.flatMap((q,i)=>[q,second[i]]);
 });
}
